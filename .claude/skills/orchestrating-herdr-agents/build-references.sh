#!/usr/bin/env bash
# Cut the orchestrator manifest into this skill's reference files, verbatim.
# The manifest is the single source of truth; every file under references/ is generated.
#
#   bash build-references.sh [manifest]           regenerate references/
#   bash build-references.sh --check [manifest]   exit 1 if references/ is not the current cut
#
# The default manifest is the repository's docs/orchestrator-manifest.md, found from this
# script's physical location (the skill may be reached through a symlink).
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
check=0
if [ "${1:-}" = --check ]; then check=1; shift; fi
manifest="${1:-$here/../../../docs/orchestrator-manifest.md}"
[ -f "$manifest" ] || { echo "manifest not found: $manifest" >&2; exit 2; }

# file | first heading, inclusive (empty = top of the manifest) | next heading, exclusive (empty = end)
parts=(
  "roles.md||## 2. "
  "herdr.md|## 2. |## 5. "
  "executors.md|## 5. |## 7. "
  "pipeline.md|## 7. |## 10. "
  "decisions.md|## 10. |## 10a. "
  "product-brainstorm.md|## 10a. |## 11. "
  "verify-and-safety.md|## 11. |## 15. "
  "operator-and-project.md|## 15. |"
)

cut_into() {
  local out="$1" blob part name from to
  blob="$(git hash-object "$manifest")"
  for part in "${parts[@]}"; do
    IFS='|' read -r name from to <<<"$part"
    {
      printf '<!-- Generated by build-references.sh from the orchestrator manifest (git blob %s). Do not edit: change the manifest and regenerate. -->\n\n' "$blob"
      awk -v from="$from" -v to="$to" '
        !started && (from == "" || index($0, from) == 1) { on = 1; started = 1 }
        on && to != "" && index($0, to) == 1 { on = 0 }
        on' "$manifest"
    } > "$out/$name"
  done
}

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
cut_into "$tmp"

# Every manifest line must land in exactly one file, in order.
for part in "${parts[@]}"; do
  IFS='|' read -r name _ _ <<<"$part"
  tail -n +3 "$tmp/$name"
done | cmp -s - "$manifest" || { echo "the cut does not reproduce the manifest exactly" >&2; exit 1; }

if [ "$check" = 1 ]; then
  if diff -r "$tmp" "$here/references" >/dev/null; then
    echo "references/ match $manifest"
  else
    echo "references/ are stale: run bash build-references.sh" >&2
    exit 1
  fi
else
  rm -rf "$here/references"
  mkdir -p "$here/references"
  cp "$tmp"/*.md "$here/references/"
  echo "wrote $(ls "$here/references" | wc -l | tr -d ' ') files to $here/references"
fi
